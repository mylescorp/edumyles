"""Generates styles/tokens.css and src/*.ts from tokens.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "tokens.json").read_text())
P = DATA["primitives"]
S = DATA["semantic"]
O = {key: value for key, value in DATA.items() if key not in {"primitives", "semantic"}}
def ts(n,o): (ROOT / f"src/{n}.ts").write_text(f"export const {n} = {json.dumps(o,indent=2)} as const;\n")
ts("primitives",P); ts("semantic",S)
for k in ["fontFamily","typography","spacing","radius","shadow","motion","layout","breakpoints","component"]: ts(k,O[k])
(ROOT / "src/index.ts").write_text("".join(f'export * from "./{n}";\n' for n in ["primitives","semantic","fontFamily","typography","spacing","radius","shadow","motion","layout","breakpoints","component","tenant","contrast"]))
def rgb(value):
    n=int(value.lstrip("#"),16)
    return f"{(n >> 16) & 255} {(n >> 8) & 255} {n & 255}"
c='/* Generated by scripts/build.py from tokens.json. Tailwind CSS v3 compatible. */\n:root {\n'
for n,sc in P.items():
    for s,v in sc.items(): c+=f"  --{n}-{s}: {v};\n"
for n,sc in P.items():
    for s,v in sc.items(): c+=f"  --{n}-{s}-rgb: {rgb(v)};\n"
c+="}\n\n:root {\n  color-scheme: light;\n  --tenant-primary: var(--teal-700);\n  --tenant-primary-foreground: #FFFFFF;\n  --tenant-primary-dark: #5BB4AA;\n  --tenant-primary-dark-foreground: #10201E;\n  --tenant-accent: "+S["light"]["accent"]+";\n"
m={"primary":"var(--tenant-primary)","primary-foreground":"var(--tenant-primary-foreground)","accent":"var(--tenant-accent)"}
for k,v in S["light"].items(): c+=f"  --{k}: {m.get(k,v)};\n"
for k,v in S["light"].items():
    actual={"primary":P["teal"]["700"],"primary-foreground":P["neutral"]["0"],"accent":S["light"]["accent"]}.get(k,v)
    c+=f"  --{k}-rgb: {rgb(actual)};\n"
c+="  --platform-chrome: var(--navy-700);\n  --platform-chrome-rgb: "+rgb(P["navy"]["700"])+";\n}\n\n.dark {\n  color-scheme: dark;\n"
md={"primary":"var(--tenant-primary-dark)","primary-foreground":"var(--tenant-primary-dark-foreground)"}
for k,v in S["dark"].items(): c+=f"  --{k}: {md.get(k,v)};\n"
for k,v in S["dark"].items():
    actual={"primary":"#5BB4AA","primary-foreground":"#10201E"}.get(k,v)
    c+=f"  --{k}-rgb: {rgb(actual)};\n"
c+='}\n\n:root {\n  --font-sans: "Inter", system-ui, sans-serif;\n'
for k,v in O["spacing"].items(): c+=f"  --spacing-{k}: {v}px;\n"
for k,v in O["layout"].items(): c+=f"  --layout-{k}: {v/16}rem;\n"
for k,v in O["component"]["radius"].items(): c+=f"  --radius-{k}: {v}px;\n"
for k,v in O["component"]["control"].items(): c+=f"  --control-{k}: {v}px;\n"
for k,v in O["shadow"].items(): c+=f"  --shadow-{k}: {v};\n"
for k,v in O["motion"].items(): c+=f"  --motion-{k}: {v}ms;\n"
c+="  --focus-ring: 0 0 0 2px var(--background), 0 0 0 4px var(--ring);\n}\n@media (pointer: coarse) { :root { --control-md: 48px; } }\n@media (prefers-reduced-motion: reduce) { :root { --motion-instant: 0ms; --motion-fast: 0ms; --motion-normal: 0ms; --motion-slow: 0ms; } }\n"
(ROOT / "styles/tokens.css").write_text(c)
